import React, { useState } from 'react';
import { Button, Dialog, Form, Input, List } from 'antd-mobile';
import { useMutation } from '@apollo/client/react';

import {
  MOBILE_DISABLE_TWO_FACTOR,
  MOBILE_ENABLE_TWO_FACTOR,
  MOBILE_START_TWO_FACTOR_SETUP,
} from '../gql';
import { useCurrentUser } from '../hooks';
import {
  Page,
  PageLoading,
  showError,
  showSuccess,
  useNavigateBack,
} from '../layout';
import { copyText } from '../utilities';
import { AccountPaths } from './paths';

interface CodeFormValues {
  code: string;
}

interface Setup {
  qrCodeSvg: string;
  secret: string;
}

const CodeItem = () => (
  <Form.Item
    label="Verification code"
    name="code"
    rules={[{ required: true, message: 'Please enter the code from your authenticator app.' }]}
  >
    <Input autoComplete="one-time-code" inputMode="numeric" maxLength={6} clearable />
  </Form.Item>
);

/**
 * Turns two-factor authentication (a code from an authenticator app such as
 * Google Authenticator) on or off for the signed-in user. Optional.
 */
export const TwoFactorScreen = () => {
  const navigateBack = useNavigateBack(AccountPaths.account);
  const { user, userLoading } = useCurrentUser();
  const [form] = Form.useForm<CodeFormValues>();
  const [setup, setSetup] = useState<Setup | null>(null);
  const [startSetup, { loading: starting }] = useMutation(MOBILE_START_TWO_FACTOR_SETUP);
  const [enableTwoFactor, { loading: enabling }] = useMutation(MOBILE_ENABLE_TWO_FACTOR);
  const [disableTwoFactor, { loading: disabling }] = useMutation(MOBILE_DISABLE_TWO_FACTOR);

  const enabled = user?.twoFactorEnabled === true;

  const handleStartSetup = async () => {
    try {
      const { data } = await startSetup();
      const { qrCodeSvg, secret } = data?.startTwoFactorSetup ?? {};
      if (qrCodeSvg && secret) setSetup({ qrCodeSvg, secret });
    } catch (error) {
      showError(error, 'Could not start the setup.');
    }
  };

  const handleCopySecret = async () => {
    if (!setup) return;
    try {
      await copyText(setup.secret);
      showSuccess('Setup key copied.');
    } catch (error) {
      showError(error, 'Could not copy the setup key.');
    }
  };

  const handleEnable = async ({ code }: CodeFormValues) => {
    try {
      await enableTwoFactor({ variables: { code: code.trim() } });
      showSuccess('Two-factor authentication is on.');
      navigateBack();
    } catch (error) {
      form.resetFields();
      showError(error, 'Could not turn on two-factor authentication.');
    }
  };

  const handleDisable = async ({ code }: CodeFormValues) => {
    const confirmed = await Dialog.confirm({
      content: 'Turn off two-factor authentication? You will sign in with only your password.',
      confirmText: <span className="two-factor-danger-text">Turn off</span>,
      cancelText: 'Cancel',
    });
    if (!confirmed) return;

    try {
      await disableTwoFactor({ variables: { code: code.trim() } });
      showSuccess('Two-factor authentication is off.');
      navigateBack();
    } catch (error) {
      form.resetFields();
      showError(error, 'Could not turn off two-factor authentication.');
    }
  };

  let content: React.ReactNode;
  if (userLoading && !user) {
    content = <PageLoading />;
  } else if (enabled) {
    content = (
      <>
        <p className="page-hint">
          Two-factor authentication is on. To turn it off, enter the current code from your
          authenticator app.
        </p>
        <Form
          form={form}
          layout="vertical"
          mode="card"
          onFinish={handleDisable}
          footer={
            <Button block color="danger" loading={disabling} size="large" type="submit">
              Turn off
            </Button>
          }
        >
          <CodeItem />
        </Form>
      </>
    );
  } else if (setup) {
    content = (
      <>
        <p className="page-hint">
          Add this account to your authenticator app (for example Google Authenticator) by
          scanning the QR code or entering the setup key, then enter the 6-digit code it shows.
        </p>
        <div
          className="two-factor-qr"
          // The SVG is generated by the server from the setup URI.
          dangerouslySetInnerHTML={{ __html: setup.qrCodeSvg }}
        />
        <List mode="card">
          <List.Item
            description={<span className="two-factor-secret">{setup.secret}</span>}
            extra="Copy"
            onClick={handleCopySecret}
          >
            Setup key
          </List.Item>
        </List>
        <Form
          form={form}
          layout="vertical"
          mode="card"
          onFinish={handleEnable}
          footer={
            <Button block color="primary" loading={enabling} size="large" type="submit">
              Turn on
            </Button>
          }
        >
          <CodeItem />
        </Form>
      </>
    );
  } else {
    content = (
      <>
        <p className="page-hint">
          Two-factor authentication adds a second step when you sign in: after your password, you
          enter a 6-digit code from an authenticator app such as Google Authenticator. It is
          optional. If you lose your phone, an administrator can turn it off for you.
        </p>
        <div className="two-factor-actions">
          <Button block color="primary" loading={starting} size="large" onClick={handleStartSetup}>
            Set up
          </Button>
        </div>
      </>
    );
  }

  return (
    <Page backTo={AccountPaths.account} title="Two-factor authentication">
      {content}
    </Page>
  );
};
