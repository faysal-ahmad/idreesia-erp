import React, { useState } from 'react';
import { Alert, Button, Flex, Form, Input, Modal, Spin, Typography } from 'antd';
import { useMutation, useQuery } from '@apollo/client/react';
import { message } from '/imports/ui/antd-feedback';

import {
  DISABLE_TWO_FACTOR,
  ENABLE_TWO_FACTOR,
  START_TWO_FACTOR_SETUP,
  TWO_FACTOR_STATUS,
} from './gql';

const { Paragraph, Text } = Typography;

interface Props {
  showForm?: boolean;
  handleClose(): void;
}

interface CodeFormValues {
  code: string;
}

interface Setup {
  qrCodeSvg: string;
  secret: string;
}

/**
 * Lets the logged-in user turn two-factor authentication (a code from an
 * authenticator app such as Google Authenticator) on or off for their own
 * account. Optional: nobody is required to use it.
 */
const TwoFactorForm = ({ showForm, handleClose }: Props) => {
  const [form] = Form.useForm<CodeFormValues>();
  const [setup, setSetup] = useState<Setup | null>(null);
  const { data, loading } = useQuery(TWO_FACTOR_STATUS, { skip: !showForm });
  const [startSetup, { loading: starting }] = useMutation(
    START_TWO_FACTOR_SETUP
  );
  const [enableTwoFactor, { loading: enabling }] =
    useMutation(ENABLE_TWO_FACTOR);
  const [disableTwoFactor, { loading: disabling }] =
    useMutation(DISABLE_TWO_FACTOR);

  const enabled = data?.currentUser?.twoFactorEnabled === true;

  const close = () => {
    form.resetFields();
    setSetup(null);
    handleClose();
  };

  const handleStartSetup = () => {
    startSetup()
      .then(({ data: result }) => {
        const { qrCodeSvg, secret } = result?.startTwoFactorSetup ?? {};
        if (qrCodeSvg && secret) setSetup({ qrCodeSvg, secret });
      })
      .catch((error: Error) => {
        message.error(error.message, 5);
      });
  };

  const handleSubmit = () => {
    form.validateFields().then(({ code }) => {
      const mutate = enabled ? disableTwoFactor : enableTwoFactor;
      mutate({ variables: { code: code.trim() } })
        .then(() => {
          message.success(
            enabled
              ? 'Two-factor authentication has been turned off.'
              : 'Two-factor authentication has been turned on.',
            5
          );
          close();
        })
        .catch((error: Error) => {
          form.resetFields();
          message.error(error.message, 5);
        });
    });
  };

  const codeField = (
    <Form form={form} layout="vertical" onFinish={handleSubmit}>
      <Form.Item
        name="code"
        label="Verification code"
        rules={[
          {
            required: true,
            message: 'Please input the code from your authenticator app.',
          },
        ]}
      >
        <Input
          autoComplete="one-time-code"
          inputMode="numeric"
          maxLength={6}
          placeholder="6-digit code"
          style={{ width: 200 }}
        />
      </Form.Item>
    </Form>
  );

  let content: React.ReactNode;
  let footer: React.ReactNode;
  if (loading) {
    content = (
      <Flex justify="center">
        <Spin />
      </Flex>
    );
    footer = null;
  } else if (enabled) {
    content = (
      <>
        <Alert
          type="success"
          showIcon
          message="Two-factor authentication is on."
          style={{ marginBottom: 16 }}
        />
        <Paragraph>
          To turn it off, enter the current code from your authenticator app.
        </Paragraph>
        {codeField}
      </>
    );
    footer = [
      <Button key="cancel" onClick={close}>
        Cancel
      </Button>,
      <Button key="disable" danger loading={disabling} onClick={handleSubmit}>
        Turn Off
      </Button>,
    ];
  } else if (setup) {
    content = (
      <>
        <Paragraph>
          Scan this QR code with your authenticator app (for example Google
          Authenticator), then enter the 6-digit code it shows.
        </Paragraph>
        <Flex justify="center">
          <div
            style={{ width: 200, height: 200 }}
            // The SVG is generated by the server from the setup URI.
            dangerouslySetInnerHTML={{ __html: setup.qrCodeSvg }}
          />
        </Flex>
        <Paragraph style={{ textAlign: 'center' }}>
          Can't scan it? Enter this key instead:
          <br />
          <Text code copyable>
            {setup.secret}
          </Text>
        </Paragraph>
        {codeField}
      </>
    );
    footer = [
      <Button key="cancel" onClick={close}>
        Cancel
      </Button>,
      <Button
        key="enable"
        type="primary"
        loading={enabling}
        onClick={handleSubmit}
      >
        Turn On
      </Button>,
    ];
  } else {
    content = (
      <>
        <Paragraph>
          Two-factor authentication adds a second step when you log in: after
          your password, you enter a 6-digit code from an authenticator app on
          your phone, such as Google Authenticator.
        </Paragraph>
        <Paragraph type="secondary">
          If you lose your phone, an administrator can turn it off for you.
        </Paragraph>
      </>
    );
    footer = [
      <Button key="cancel" onClick={close}>
        Cancel
      </Button>,
      <Button
        key="start"
        type="primary"
        loading={starting}
        onClick={handleStartSetup}
      >
        Set Up
      </Button>,
    ];
  }

  return (
    <Modal
      title="Two-Factor Authentication"
      open={showForm}
      onCancel={close}
      footer={footer}
      destroyOnHidden
    >
      {content}
    </Modal>
  );
};

export default TwoFactorForm;
